-- ============================================================================
--  jobs  —  job listings
--
--  Run this once in the Supabase SQL editor (project: pkpbzthkwskkudqogyrl).
--  No storage bucket, no uploads — just one table and two policies.
-- ============================================================================

create table if not exists public.jobs (
  id           bigint        generated by default as identity primary key,

  title        text          not null check (length(trim(title)) > 0),
  description  text          not null check (length(trim(description)) > 0),

  -- A range, stored as two numbers. The rule at the bottom of the table
  -- makes sure the maximum can never be smaller than the minimum.
  salary_min   numeric(10,2) not null check (salary_min >= 0),
  salary_max   numeric(10,2) not null check (salary_max >= 0),

  start_date   date          not null,

  -- Cities only in New Zealand and Australia. Anything else is refused by the
  -- database itself — not just by the form.
  -- NOTE: the dropdown in jobs.html lists the same cities. If you add one here,
  -- add it there too.
  city         text          not null check (city in (
                               -- New Zealand
                               'Auckland', 'Wellington', 'Christchurch', 'Hamilton',
                               'Tauranga', 'Dunedin', 'Palmerston North', 'Napier',
                               'Nelson', 'Queenstown', 'Rotorua', 'Invercargill',
                               -- Australia
                               'Sydney', 'Melbourne', 'Brisbane', 'Perth', 'Adelaide',
                               'Gold Coast', 'Canberra', 'Newcastle', 'Hobart',
                               'Darwin', 'Wollongong', 'Geelong', 'Cairns', 'Townsville'
                             )),

  -- Filled in with whoever is logged in. The browser never sends this.
  created_by   uuid          not null default auth.uid()
                             references auth.users (id) on delete cascade,

  created_at   timestamptz   not null default now(),

  -- Table-level rule: it needs both columns, so it can't live on one of them.
  constraint salary_range_makes_sense check (salary_max >= salary_min)
);

-- ---------------------------------------------------------------------------
--  1. Switch RLS on. Without this, the table answers anyone with the
--     publishable key and every policy below is ignored.
-- ---------------------------------------------------------------------------
alter table public.jobs enable row level security;

-- ---------------------------------------------------------------------------
--  2. READING — anyone can browse the job board, logged in or not.
-- ---------------------------------------------------------------------------
create policy "jobs are public to read"
on public.jobs
for select
to anon, authenticated
using ( true );

-- ---------------------------------------------------------------------------
--  3. POSTING — logged-in people only, and only as themselves.
-- ---------------------------------------------------------------------------
create policy "logged-in users can post a job"
on public.jobs
for insert
to authenticated
with check ( auth.uid() = created_by );

