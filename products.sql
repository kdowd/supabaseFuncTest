create table if not exists public.products (
  id          bigint        generated by default as identity primary key,
  title       text          not null,
  price       numeric(10,2) not null default 0 check (price >= 0),
  image_url   text,

  -- Filled in automatically with whoever is logged in. You never send this
  -- from the browser — the database works it out from their session.
  created_by  uuid          not null default auth.uid()
                            references auth.users (id) on delete cascade,

  created_at  timestamptz   not null default now()
);

-- ---------------------------------------------------------------------------
--  1. Switch RLS on. Until you do this, every policy below is ignored and the
--     table answers anyone holding the publishable key.
-- ---------------------------------------------------------------------------
alter table public.products enable row level security;

-- ---------------------------------------------------------------------------
--  2. READING — public. Anyone, logged in or not, can see the cards.
--     "using ( true )" means "every row is fine to read".
-- ---------------------------------------------------------------------------
create policy "cards are public to read"
on public.products
for select
to anon, authenticated
using ( true );

-- ---------------------------------------------------------------------------
--  3. ADDING — logged-in people only, and only as themselves.
--     with check runs against the NEW row, so it stops anyone inserting a card
--     that claims to be written by somebody else.
-- ---------------------------------------------------------------------------
create policy "logged-in users can add a card"
on public.products
for insert
to authenticated
with check ( auth.uid() = created_by );

